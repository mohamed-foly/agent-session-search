import { randomUUID } from 'crypto';
import { IndexedMessage, RebuiltTranscript, SessionMeta } from './types';

/**
 * Rebuilds a resumable Claude Code transcript from indexed messages.
 *
 * The index stores each JSONL line as flattened string values (keys dropped,
 * see textExtract.ts), so the original tool_use/tool_result structure can't be
 * restored. Instead this produces a text-only conversation that `claude
 * --resume` accepts: real user prompts stay user turns, and everything the
 * assistant did in between (replies, tool calls, tool output) is folded into
 * one assistant text turn per exchange, with tool payloads truncated.
 *
 * Flattened shapes this relies on (first lines of the indexed text):
 *   assistant: "text\n<reply>" | "tool_use\n<id>\n<name>\n<input…>" | "thinking"
 *   user:      "<prompt>" | "text\n<prompt>" | "<toolu_id>\ntool_result\n<output>"
 *              | "tool_result\n<output>\n<toolu_id>"
 */

/**
 * Set on every line a rebuild writes. Claude Code ignores unknown fields and
 * resuming only appends, so the flag lets the adapter tell rebuilt history
 * apart from real turns added later.
 */
export const REBUILT_LINE_FLAG = 'rebuiltFromIndex';

const TOOL_INPUT_CHARS = 1500;
const TOOL_OUTPUT_CHARS = 1500;
/** Recorded as the transcript's CLI version; any 2.x Claude Code resumes it. */
const TRANSCRIPT_VERSION = '2.1.246';

type Role = 'user' | 'assistant';
interface Turn {
  role: Role;
  timestamp: string | null;
  chunks: string[];
}

function clip(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, max)}\n… [${text.length - max} chars truncated]`;
}

/** Returns the tool output if this user-role line is a tool result, else null. */
function toolResultBody(text: string): string | null {
  let body: string | null = null;
  if (text.startsWith('toolu_')) {
    const marker = '\ntool_result\n';
    const at = text.indexOf(marker);
    if (at !== -1 && at < 80) body = text.slice(at + marker.length);
  } else if (text.startsWith('tool_result\n')) {
    body = text.slice('tool_result\n'.length);
  }
  if (body === null) return null;
  // Content given as [{type:'text', text}] blocks flattens with a "text" prefix.
  return body.replace(/\ntoolu_\w+$/, '').replace(/^text\n/, '');
}

/** User-role lines the CLI injects (not typed by the user). */
function isInjectedUserText(text: string): boolean {
  return (
    text.startsWith('<local-command') ||
    text.startsWith('<command-') ||
    text.startsWith('<system-reminder>') ||
    text.startsWith('Caveat: The messages below were generated by the user while running local commands')
  );
}

export function buildClaudeCodeTranscript(
  session: SessionMeta,
  messages: IndexedMessage[]
): RebuiltTranscript {
  const turns: Turn[] = [];
  const push = (role: Role, timestamp: string | null, chunk: string) => {
    const last = turns[turns.length - 1];
    if (last && last.role === role) last.chunks.push(chunk);
    else turns.push({ role, timestamp, chunks: [chunk] });
  };
  const lastChunk = () => {
    const last = turns[turns.length - 1];
    return last ? last.chunks[last.chunks.length - 1] : '';
  };

  for (const message of messages) {
    let text = message.text.trim();
    if (message.role === 'user') {
      const result = toolResultBody(text);
      if (result !== null) {
        // AskUserQuestion answers arrive as tool results but are real user input.
        if (result.startsWith('The user answered')) push('user', message.timestamp, result);
        else push('assistant', message.timestamp, `⎿ result:\n${clip(result, TOOL_OUTPUT_CHARS)}`);
        continue;
      }
      if (text.startsWith('text\n')) text = text.slice('text\n'.length);
      if (!text || isInjectedUserText(text)) continue;
      // A loaded skill's body is injected as a user line right after the Skill call.
      if (turns[turns.length - 1]?.role === 'assistant' && lastChunk().includes('Launching skill')) {
        push('assistant', message.timestamp, `[skill content loaded]\n${clip(text, TOOL_OUTPUT_CHARS)}`);
        continue;
      }
      push('user', message.timestamp, text);
    } else if (message.role === 'assistant') {
      if (text === 'thinking' || text.startsWith('thinking\n')) continue;
      if (text.startsWith('text\n')) {
        push('assistant', message.timestamp, text.slice('text\n'.length));
      } else if (text.startsWith('tool_use\n')) {
        const [, , name, ...input] = text.split('\n');
        push('assistant', message.timestamp, `[tool ${name}]\n${clip(input.join('\n'), TOOL_INPUT_CHARS)}`);
      } else {
        push('assistant', message.timestamp, text);
      }
    }
    // Other roles (attachment, system, file-history-snapshot, …) are metadata.
  }

  while (turns.length && turns[0].role !== 'user') turns.shift();
  if (turns.length) {
    turns[0].chunks.unshift(
      `[Reconstructed session: rebuilt by agent-session-search on ${new Date().toISOString().slice(0, 10)} ` +
        'from its search index. Text-only; tool calls and results are summarized and truncated.]'
    );
  }

  const common = {
    isSidechain: false,
    userType: 'external',
    entrypoint: 'cli',
    cwd: session.cwd,
    sessionId: session.sessionId,
    version: TRANSCRIPT_VERSION,
    gitBranch: 'HEAD',
  };
  const fallbackTimestamp = session.endedAt ?? new Date().toISOString();

  let parentUuid: string | null = null;
  const lines: string[] = [];
  for (const turn of turns) {
    const uuid = randomUUID();
    const body = turn.chunks.join('\n\n');
    const message =
      turn.role === 'user'
        ? { role: 'user', content: body }
        : {
            model: 'claude-rebuilt',
            id: `msg_rebuilt_${uuid.slice(0, 8)}`,
            type: 'message',
            role: 'assistant',
            content: [{ type: 'text', text: body }],
            stop_reason: 'end_turn',
            stop_sequence: null,
            usage: { input_tokens: 0, output_tokens: 0 },
          };
    lines.push(
      JSON.stringify({
        parentUuid,
        type: turn.role,
        message,
        ...common,
        [REBUILT_LINE_FLAG]: true,
        uuid,
        timestamp: turn.timestamp ?? fallbackTimestamp,
      })
    );
    parentUuid = uuid;
  }

  return {
    content: lines.length ? `${lines.join('\n')}\n` : '',
    userTurns: turns.filter((t) => t.role === 'user').length,
    assistantTurns: turns.filter((t) => t.role === 'assistant').length,
  };
}
